import { writeFileSync } from 'node:fs';
import type { Exercise, Item, LessonNode, LessonPack } from '../../src/schema/pack';

type ExBody = Exercise extends infer E ? (E extends Exercise ? Omit<E, 'id'> : never) : never;

function node(
  id: string,
  kind: LessonNode['kind'],
  title: string,
  introduces: string[],
  teach: LessonNode['teach'],
  exercises: ExBody[],
): LessonNode {
  return {
    id,
    kind,
    title,
    introduces,
    ...(teach ? { teach } : {}),
    exercises: exercises.map(
      (e, i) => ({ id: `${id}.e${String(i + 1).padStart(2, '0')}`, ...e }) as Exercise,
    ),
  };
}

